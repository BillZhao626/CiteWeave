def build():
    docs = [{"id": f"target-{i:03}", "text": a, "scope": "primary"} for i, (_, a) in enumerate(PAIRS)]
    topics = [
        "机房巡检",
        "键盘采购",
        "食堂排班",
        "会议预订",
        "公园照明",
        "仓库运输",
        "图书借阅",
        "展馆门票",
        "水质采样",
        "自行车维护",
        "气象观测",
        "园艺灌溉",
        "游泳训练",
        "音乐排练",
        "果树施肥",
    ]
    for i in range(970):
        topic = topics[i % len(topics)]
        docs.append(
            {
                "id": f"background-{i:04}",
                "scope": "primary",
                "text": f"{topic}记录第{i + 1}号：本次检查完成了清单核对，负责人在周{1 + i % 7}提交报告。"
                f"区域编号为{i % 53}，计划处理{2 + i % 13}项事项，异常情况由值班人员联系处理。",
            }
        )
    queries = [
        {"id": f"q{i:02}", "text": q, "relevant": [f"target-{i:03}"]} for i, (q, _) in enumerate(PAIRS)
    ]
    return docs, queries


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1] / ".artifacts" / "p02"
    root.mkdir(parents=True, exist_ok=True)
    docs, queries = build()
